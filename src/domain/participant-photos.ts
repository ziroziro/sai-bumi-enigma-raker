function normalizeLookupName(raw?: string | null): string {
  if (!raw) return "";
  return raw
    .replace(/[^a-zA-Z0-9\s]/g, " ")
    .replace(/\s+/g, " ")
    .trim()
    .toUpperCase();
}

export function getParticipantPhotoUrl(
  nikOrCode?: string | null,
  fullName?: string | null
): string | null {
  if (nikOrCode) {
    const cleanNik = nikOrCode.trim().toUpperCase();
    if (PHOTO_BY_NIK[cleanNik]) return PHOTO_BY_NIK[cleanNik]!;
  }
  const cleanName = normalizeLookupName(fullName);
  if (cleanName && PHOTO_BY_NAME[cleanName]) {
    return PHOTO_BY_NAME[cleanName]!;
  }
  return null;
}
